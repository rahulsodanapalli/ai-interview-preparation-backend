"""Pinecone Standard Dense Vector Storage Service for RAG document chunk storage and retrieval.

Manages upsertion of 768-dimensional embedding vectors and safe metadata into Pinecone standard dense-vector indexes,
similarity search with document-scoped isolation filters, index configuration verification,
and document vector deletion.
"""

import asyncio
import logging
from typing import Any, Dict, List, Optional

try:
    from pinecone import Pinecone
    import pinecone.exceptions as pce
    HAS_PINECONE = True
except ImportError:  # pragma: no cover
    HAS_PINECONE = False
    Pinecone = None
    pce = None

from app.core.config import settings
from app.services.chunking_service import TextChunk

logger = logging.getLogger(__name__)


# ============================================================================
# Pinecone Custom Exceptions
# ============================================================================


class PineconeServiceError(Exception):
    """Base exception for Pinecone vector storage operations."""

    pass


class PineconeConfigurationError(PineconeServiceError):
    """Raised when required Pinecone configuration (e.g. API key) is missing or invalid."""

    pass


class PineconeConnectionError(PineconeServiceError):
    """Raised when connection to the Pinecone service fails."""

    pass


class PineconeTimeoutError(PineconeServiceError):
    """Raised when an operation to Pinecone times out."""

    pass


class PineconeIndexNotFoundError(PineconeServiceError):
    """Raised when the specified Pinecone index does not exist."""

    pass


class PineconeDimensionMismatchError(PineconeServiceError):
    """Raised when index dimension or vector dimension is incompatible."""

    pass


class PineconeResponseError(PineconeServiceError):
    """Raised when Pinecone returns an unexpected response or API error."""

    pass


# ============================================================================
# Pinecone Service Implementation
# ============================================================================


class PineconeService:
    """Service wrapper for Pinecone standard dense-vector operations (upsert, query, delete).

    Stores 768-dimensional float embedding vectors generated by Ollama nomic-embed-text
    in Pinecone standard dense-vector indexes with document-scoped isolation metadata.
    Numeric embeddings are stored strictly in vector values, never in metadata.

    Attributes:
        api_key: Pinecone API key (never logged).
        index_name: Name of target Pinecone standard index (e.g. 'ai-interview-prep-v2').
        namespace: Target vector namespace.
        top_k: Default retrieval top_k.
        dimension: Expected vector dimension (768 for nomic-embed-text).
        metric: Expected similarity metric ('cosine').
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        index_name: Optional[str] = None,
        namespace: Optional[str] = None,
        top_k: Optional[int] = None,
        dimension: Optional[int] = None,
        metric: Optional[str] = None,
        **kwargs: Any,
    ):
        self.api_key = api_key if api_key is not None else settings.PINECONE_API_KEY
        self.index_name = index_name or settings.PINECONE_INDEX_NAME
        self.namespace = namespace or settings.PINECONE_NAMESPACE
        self.top_k = top_k or settings.PINECONE_TOP_K
        self.dimension = dimension or settings.PINECONE_DIMENSION
        self.metric = metric or settings.PINECONE_METRIC

        self._client: Optional[Any] = None
        self._index: Optional[Any] = None

    def get_client(self) -> Any:
        """Initializes and returns the Pinecone client instance.

        Raises:
            PineconeConfigurationError: If PINECONE_API_KEY is not configured.
            PineconeConnectionError: If client instantiation fails.
        """
        if not self.api_key or not str(self.api_key).strip():
            raise PineconeConfigurationError(
                "Pinecone API key is not configured. Please set the PINECONE_API_KEY environment variable."
            )

        if not HAS_PINECONE:  # pragma: no cover
            raise PineconeConfigurationError(
                "The 'pinecone' package is not installed. Run 'pip install pinecone>=5.0.0'."
            )

        if self._client is None:
            try:
                self._client = Pinecone(api_key=self.api_key)
            except Exception as exc:
                logger.error("Failed to initialize Pinecone client: %s", exc)
                raise PineconeConnectionError(f"Failed to initialize Pinecone client: {exc}") from exc

        return self._client

    def get_index(self) -> Any:
        """Retrieves or creates the Pinecone Index handle.

        Raises:
            PineconeConfigurationError: If API key is missing.
            PineconeIndexNotFoundError: If index cannot be found.
        """
        if self._index is not None:
            return self._index

        client = self.get_client()
        try:
            self._index = client.Index(self.index_name)
            return self._index
        except Exception as exc:
            logger.error("Failed to connect to Pinecone index '%s': %s", self.index_name, exc)
            raise PineconeIndexNotFoundError(
                f"Failed to access Pinecone index '{self.index_name}': {exc}"
            ) from exc

    async def verify_index(self) -> Dict[str, Any]:
        """Verifies connectivity to Pinecone and checks index dimension, metric, and type compatibility.

        Returns:
            Dict containing index status, dimension, and metric.

        Raises:
            PineconeConfigurationError: If API key is missing.
            PineconeIndexNotFoundError: If index does not exist.
            PineconeDimensionMismatchError: If index dimension does not match 768 or index is not a standard vector index.
            PineconeConnectionError: If connection fails.
        """
        client = self.get_client()

        def _verify():
            try:
                if not client.has_index(self.index_name):
                    raise PineconeIndexNotFoundError(
                        f"Pinecone index '{self.index_name}' does not exist. "
                        f"Please create a standard dense-vector index with dimension={self.dimension} and metric='{self.metric}'."
                    )
                desc = client.describe_index(self.index_name)
                idx_dim = getattr(desc, "dimension", None) or (desc.get("dimension") if isinstance(desc, dict) else None)
                idx_metric = getattr(desc, "metric", None) or (desc.get("metric") if isinstance(desc, dict) else None)

                if idx_dim is not None and idx_dim != self.dimension:
                    raise PineconeDimensionMismatchError(
                        f"Pinecone index '{self.index_name}' has dimension {idx_dim}, "
                        f"but embedding model requires dimension {self.dimension}."
                    )

                # Check if this index was configured as a document index with integrated embedding
                schema = getattr(desc, "schema", None) or (desc.get("schema") if isinstance(desc, dict) else None)
                if schema:
                    raise PineconeDimensionMismatchError(
                        f"Pinecone index '{self.index_name}' is configured as a document index with schema fields, "
                        f"not a standard dense-vector index. "
                        f"Please create a standard dense-vector index with dimension={self.dimension} and metric='{self.metric}'."
                    )

                return {
                    "index_name": self.index_name,
                    "dimension": idx_dim,
                    "metric": idx_metric,
                    "status": "ready",
                }
            except (PineconeIndexNotFoundError, PineconeDimensionMismatchError):
                raise
            except Exception as exc:
                logger.error("Error verifying Pinecone index '%s': %s", self.index_name, exc)
                raise PineconeConnectionError(f"Error verifying Pinecone index: {exc}") from exc

        return await asyncio.to_thread(_verify)

    async def upsert_document_chunks(
        self,
        document_id: str,
        chunks: List[TextChunk],
        vectors: List[List[float]],
        filename: str,
        namespace: Optional[str] = None,
        batch_size: int = 100,
    ) -> int:
        """Upserts text chunks and 768-dim embedding vectors into Pinecone standard dense index.

        Deterministic Chunk ID Format:
            f"{document_id}#chunk_{chunk.index}"

        Vectors are passed as (id, vector, metadata) tuples, where the numeric
        embedding is stored strictly in the vector values, NEVER in metadata.

        Supported metadata fields:
            document_id: Unique document identifier.
            chunk_index: Integer index of chunk within document.
            filename: Original PDF filename.
            text: Chunk text content.
            character_count: Length of chunk in characters.
            token_estimate: Estimated token count.

        Args:
            document_id: Unique document identifier.
            chunks: List of TextChunk objects.
            vectors: Corresponding list of 768-dim float embedding vectors.
            filename: Sanitized source filename.
            namespace: Target namespace (defaults to self.namespace).
            batch_size: Maximum documents per upsert batch.

        Returns:
            Total count of upserted vectors.

        Raises:
            PineconeResponseError: If chunk and vector counts mismatch or upsert fails.
            PineconeDimensionMismatchError: If any vector does not match the expected 768 dimensions.
        """
        if not chunks:
            return 0

        if len(chunks) != len(vectors):
            raise PineconeResponseError(
                f"Mismatch between chunks count ({len(chunks)}) and vectors count ({len(vectors)})."
            )

        # Validate vector dimensions - strictly 768 dimensions required
        for i, vec in enumerate(vectors):
            if len(vec) != self.dimension:
                raise PineconeDimensionMismatchError(
                    f"Vector at index {i} has dimension {len(vec)}, but index dimension is {self.dimension}."
                )

        target_namespace = namespace if namespace is not None else self.namespace
        index = self.get_index()

        # Build standard vector records: (id, embedding, metadata)
        # embedding is placed in the vector's values; metadata contains ONLY supported fields.
        vector_records = []
        for chunk, vec in zip(chunks, vectors):
            record_id = f"{document_id}#chunk_{chunk.index}"
            meta = {
                "document_id": document_id,
                "source_id": document_id,
                "chunk_index": chunk.index,
                "filename": filename,
                "text": chunk.text,
                "character_count": chunk.character_count,
                "token_estimate": chunk.token_estimate,
            }
            vector_records.append((record_id, vec, meta))

        logger.info(
            "Upserting %d vectors for document '%s' to Pinecone index '%s' (namespace='%s').",
            len(vector_records),
            document_id,
            self.index_name,
            target_namespace,
        )

        def _do_upsert():
            total_upserted = 0
            for i in range(0, len(vector_records), batch_size):
                batch = vector_records[i : i + batch_size]
                try:
                    resp = index.upsert(vectors=batch, namespace=target_namespace)
                    count = getattr(resp, "upserted_count", None)
                    if count is None and isinstance(resp, dict):
                        count = resp.get("upserted_count")
                    total_upserted += count if isinstance(count, int) else len(batch)
                except Exception as exc:
                    logger.error("Failed to upsert vector batch to Pinecone: %s", exc)
                    raise PineconeResponseError(f"Pinecone upsert failed: {exc}") from exc
            return total_upserted

        return await asyncio.to_thread(_do_upsert)

    async def query_similar_chunks(
        self,
        query_vector: List[float],
        document_id: Optional[str] = None,
        top_k: Optional[int] = None,
        namespace: Optional[str] = None,
        filter_dict: Optional[Dict[str, Any]] = None,
    ) -> List[Dict[str, Any]]:
        """Queries the vector index for similar chunks with document-scoped isolation using standard index.query().

        Args:
            query_vector: 768-dim float query vector.
            document_id: Optional document ID to isolate retrieval scope.
            top_k: Number of nearest matches to return.
            namespace: Target namespace (defaults to self.namespace).
            filter_dict: Additional metadata filter criteria.

        Returns:
            List of matching records with id, score, text, and metadata.
        """
        if len(query_vector) != self.dimension:
            raise PineconeDimensionMismatchError(
                f"Query vector dimension {len(query_vector)} does not match expected dimension {self.dimension}."
            )

        target_top_k = top_k or self.top_k
        target_namespace = namespace if namespace is not None else self.namespace
        index = self.get_index()

        # Build metadata filter for document isolation
        combined_filter: Dict[str, Any] = {}
        if document_id:
            clean_doc_id = document_id.split("#")[0].strip() if "#" in document_id else document_id.strip()
            combined_filter["document_id"] = {"$eq": clean_doc_id}
        if filter_dict:
            for k, v in filter_dict.items():
                if isinstance(v, dict):
                    combined_filter[k] = v
                else:
                    combined_filter[k] = {"$eq": v}

        def _do_query():
            try:
                results = index.query(
                    vector=query_vector,
                    top_k=target_top_k,
                    include_metadata=True,
                    namespace=target_namespace,
                    filter=combined_filter if combined_filter else None,
                )
            except Exception as exc:
                logger.error("Error querying Pinecone index: %s", exc)
                raise PineconeResponseError(f"Pinecone query failed: {exc}") from exc

            matches = getattr(results, "matches", None)
            if matches is None and isinstance(results, dict):
                matches = results.get("matches", [])
            elif matches is None:
                matches = []

            parsed: List[Dict[str, Any]] = []
            for match in matches:
                m_id = (
                    getattr(match, "id", None)
                    or (match.get("id") if isinstance(match, dict) else "")
                )
                m_score = (
                    getattr(match, "score", None)
                    or (match.get("score") if isinstance(match, dict) else 0.0)
                )

                # Extract metadata
                meta = (
                    getattr(match, "metadata", None)
                    or (match.get("metadata") if isinstance(match, dict) else None)
                    or {}
                )
                if hasattr(meta, "to_dict"):
                    meta = meta.to_dict()
                elif not isinstance(meta, dict):
                    meta = {}

                doc_id = meta.get("document_id") or getattr(match, "document_id", document_id)
                chunk_index = meta.get("chunk_index") or getattr(match, "chunk_index", 0)
                filename = meta.get("filename") or getattr(match, "filename", "document.pdf")
                text = meta.get("text") or getattr(match, "text", "")

                parsed.append({
                    "id": m_id,
                    "score": float(m_score) if m_score is not None else 0.0,
                    "document_id": doc_id,
                    "chunk_index": int(chunk_index) if chunk_index is not None else 0,
                    "filename": filename,
                    "text": text,
                    "metadata": meta,
                })

            return parsed

        return await asyncio.to_thread(_do_query)

    async def delete_document(
        self,
        document_id: str,
        namespace: Optional[str] = None,
    ) -> bool:
        """Deletes all vectors belonging to a document_id using metadata filter on standard index.

        Args:
            document_id: Identifier of the document to purge from the index.
            namespace: Target namespace (defaults to self.namespace).

        Returns:
            True if deletion was successfully requested.
        """
        if not document_id or not document_id.strip():
            raise PineconeResponseError("document_id must not be empty for deletion.")

        clean_doc_id = document_id.strip()
        if "#" in clean_doc_id:
            clean_doc_id = clean_doc_id.split("#")[0].strip()
        target_namespace = namespace if namespace is not None else self.namespace
        index = self.get_index()

        def _do_delete():
            try:
                index.delete(
                    filter={"document_id": {"$eq": clean_doc_id}},
                    namespace=target_namespace,
                )
                logger.info(
                    "Deleted vectors for document '%s' from Pinecone (namespace='%s').",
                    clean_doc_id,
                    target_namespace,
                )
                return True
            except Exception as exc:
                logger.error("Failed to delete document '%s' from Pinecone: %s", clean_doc_id, exc)
                raise PineconeResponseError(f"Pinecone delete failed: {exc}") from exc

        return await asyncio.to_thread(_do_delete)


def get_pinecone_service() -> PineconeService:
    """FastAPI dependency provider for PineconeService."""
    return PineconeService()
